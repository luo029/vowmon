/* 单个属性倍率，未收录按 1 倍 */
function getTypeMultiplier(attacker, defender) {
    const row = typeChart[attacker];
    if (!row) return 1;
    const value = row[defender];
    return value === undefined ? 1 : value;
}

/* 双系倍率：把守方每个属性的倍率相乘 */
function getComboMultiplier(attacker, defenders) {
    return defenders.reduce((acc, defender) => acc * getTypeMultiplier(attacker, defender), 1);
}

/* 生成 18 个单系 + C(18,2)=153 个双系，共 171 种守方组合 */
function buildDefenderCombos(typeNames) {
    const combos = typeNames.map(name => [name]);
    for (let i = 0; i < typeNames.length; i++) {
        for (let j = i + 1; j < typeNames.length; j++) {
            combos.push([typeNames[i], typeNames[j]]);
        }
    }
    return combos;
}
